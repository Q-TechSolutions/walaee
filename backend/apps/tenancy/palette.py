"""
لون العلامة حين لا يختاره التاجر.

`Brand.primary_color` له افتراضي واحد، فكل علامة تُنشأ بلا لون
تخرج بنفس الأخضر. هذا غير مرئي في لوحة التاجر — هو يرى علامته
وحدها — لكنه مرئي تمامًا في محفظة العميل: بطاقتان لمتجرين
مختلفين بنفس اللون تبدوان بطاقة واحدة مكرّرة، ويفقد العميل
الإشارة البصرية التي يميّز بها متاجره بنظرة واحدة.

اللون يُشتق من الاسم لا يُسحب عشوائيًا: العلامة نفسها تأخذ نفس
اللون في كل بيئة وبعد كل إعادة إنشاء، فلا تتبدّل ألوان المحفظة
بين نشرة وأخرى. والتاجر يظل قادرًا على تغييره من إعدادات علامته —
هذا افتراضٌ أول، لا قرار نهائي.
"""

from __future__ import annotations

import hashlib

#: ألوان داكنة بما يكفي لنص أبيض فوقها، ومتباعدة في دائرة الألوان
#: حتى لا يتشابه لونان متجاوران في القائمة. مشتقّة من لوحة العلامات
#: في `network.py` لتبدو العلامة الجديدة من نفس العائلة.
PALETTE: tuple[str, ...] = (
    "#1F6F5C",  # أخضر تجاري
    "#6F4E37",  # بنّي قهوة
    "#B3392F",  # أحمر طوبي
    "#3B3F8C",  # أزرق داكن
    "#C9762B",  # برتقالي خبز
    "#B0367A",  # توتي
    "#0E6C86",  # أزرق بحري
    "#5C4B9B",  # بنفسجي
    "#127A53",  # أخضر صيدلية
    "#7A2E1E",  # عنّابي مشويّ
    "#2D6CDF",  # أزرق رياضي
    "#C2185B",  # وردي زهور
)


def brand_color(name: str) -> str:
    """
    لون ثابت لاسم العلامة.

    `hash` المدمج في بايثون معشّى عبر التشغيلات (PYTHONHASHSEED)،
    فاستعماله كان سيعطي العلامة لونًا مختلفًا بعد كل إعادة تشغيل.
    التلخيص هنا مُستخدَم كدالة توزيع لا كضمانة أمنية.
    """
    digest = hashlib.sha256(name.strip().encode("utf-8")).digest()
    return PALETTE[digest[0] % len(PALETTE)]
