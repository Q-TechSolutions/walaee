/**
 * نصف قطر فقاعة المحافظة.
 *
 * جذر تربيعي لا خطّي: العين تقارن **مساحات** الدوائر لا أقطارها،
 * فمضاعفة نصف القطر مع مضاعفة العدد تجعل محافظة بضعفَي الفروع
 * تبدو بأربعة أضعافها. الجذر يجعل المساحة تتناسب مع العدد فعلًا.
 */
export function bubbleRadius(count: number, max: number): number {
  if (count <= 0) return 0;
  const MIN = 11;
  const MAX = 34;
  const ratio = Math.sqrt(count) / Math.sqrt(Math.max(max, 1));
  return MIN + (MAX - MIN) * ratio;
}

/**
 * نصف قطر القرص المصمت داخل الهالة — وهو هدف النقر الفعلي.
 *
 * حدّ أدنى مطلق إلى جانب النسبة: محافظة بفرع واحد كان قرصها
 * ٦٫٨ بكسل، أي هدف لمس بقطر ١٤ على شاشة هاتف. القائمة المجاورة
 * للخريطة تبقى الطريق الموثوق للاختيار، لكن ما يبدو قابلًا
 * للضغط يجب أن يكون قابلًا للضغط فعلًا.
 */
export function bubbleCore(radius: number): number {
  return Math.max(radius * 0.64, 12);
}
