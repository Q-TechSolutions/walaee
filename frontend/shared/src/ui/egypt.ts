/**
 * هندسة خريطة مصر.
 *
 * لا مكتبة خرائط ولا مزوّد بلاطات (tiles). الأسباب ثلاثة وكلها
 * تشغيلية لا ذوقية:
 *
 * ١. مزوّد البلاطات طرف ثالث يرى كل زائر لصفحتنا العامة وكل موقع
 *    يبحث عنه العميل. هذا تسريب لا مبرّر له لعرض ثمانين نقطة.
 * ٢. مكتبة الخرائط تضيف ~١٥٠ كيلوبايت وتطلب صورًا من شبكة قد
 *    تكون بطيئة. الصفحة العامة تُقاس بأول رسم لها.
 * ٣. البلاطات تُرسَم بأسماء ومناطق لا نتحكّم بها، والخريطة هنا
 *    وظيفتها إثبات التغطية لا الملاحة.
 *
 * الحدّ ورسم النيل مخزّنان إحداثيات جغرافية لا مسارات SVG جاهزة،
 * ويمرّان بنفس دالة الإسقاط التي تمرّ بها العلامات. هذا هو بيت
 * القصيد: مسار مرسوم يدويًا ينحرف عن العلامات عند أي تغيير في
 * الإطار — فتظهر فروع الإسكندرية في البحر ولا يفهم أحد لماذا.
 * ما دام الاثنان من دالة واحدة، لا يمكن أن يفترقا.
 */

/** حدود الإطار — أوسع قليلًا من مصر لترك هامش بصري. */
export const BOUNDS = {
  north: 31.9,
  south: 21.7,
  west: 24.4,
  east: 37.2,
} as const;

/**
 * تصحيح خطوط الطول.
 *
 * درجة الطول أقصر من درجة العرض بمقدار جيب تمام خط العرض. بلا هذا
 * المعامل تظهر مصر ممدودة عرضًا بنحو ١٢٪ — تشوّه لا يُسمّيه الناظر
 * لكنه يجعل الشكل «غير مصر».
 */
const MID_LAT = (BOUNDS.north + BOUNDS.south) / 2;
const LNG_SCALE = Math.cos((MID_LAT * Math.PI) / 180);

const SPAN_X = (BOUNDS.east - BOUNDS.west) * LNG_SCALE;
const SPAN_Y = BOUNDS.north - BOUNDS.south;

/** أبعاد نظام الإحداثيات الداخلي — `viewBox`. */
export const VIEW = {
  width: 1000,
  height: Math.round((1000 * SPAN_Y) / SPAN_X),
};

export interface Point {
  x: number;
  y: number;
}

/** يحوّل إحداثيًا جغرافيًا إلى نقطة داخل `viewBox`. */
export function project(lat: number, lng: number): Point {
  return {
    x: ((lng - BOUNDS.west) * LNG_SCALE * VIEW.width) / SPAN_X,
    // محور Y في SVG يزيد نزولًا، وخط العرض يزيد شمالًا — فيُقلب
    y: ((BOUNDS.north - lat) * VIEW.height) / SPAN_Y,
  };
}

/** يبني مسار SVG من قائمة إحداثيات جغرافية. */
export function pathFrom(
  coords: readonly (readonly [number, number])[],
  close = false,
): string {
  const parts = coords.map(([lat, lng], index) => {
    const { x, y } = project(lat, lng);
    return `${index === 0 ? "M" : "L"}${x.toFixed(1)} ${y.toFixed(1)}`;
  });
  return parts.join(" ") + (close ? " Z" : "");
}

