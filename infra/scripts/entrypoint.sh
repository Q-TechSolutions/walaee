#!/usr/bin/env sh
# نقطة دخول الحاوية.
#
# الهجرات تُطبَّق هنا لا في أمر البناء: البناء قد يحدث على جهاز لا
# يرى قاعدة الإنتاج أصلًا.
#
# ══════════════════════════════════════════════════════════
#  قاعدة حاكمة: خطوة واحدة فقط تُسقِط الحاوية — الهجرات.
#
#  `set -e` كان يجعل أي تعثّر هنا يُنهي الحاوية، فتُعاد، فتتعثّر
#  ثانيةً: حلقة لا تنتهي والتطبيق كله مقفول خلفها. ومن الخارج لا
#  يُرى منها إلا 502 على كل نداء ‏/api/ — بينما الصفحة العامة
#  تُحمَّل لأن nginx يخدمها بنفسه. فيبدو النشر «ناجحًا وفيه أعطال».
#
#  فما لا يمنع الخدمة من العمل يُحذَّر منه ويُكمَّل: لوحة إدارة بلا
#  تنسيق، أو مهام دورية غير مثبّتة، أهون بما لا يُقاس من منصة لا
#  تردّ على أحد. والهجرة وحدها تبقى قاتلة لأن الخدمة على قاعدة
#  غير مُهاجَرة تعطي سلوكًا خاطئًا لا عطلًا ظاهرًا.
# ══════════════════════════════════════════════════════════
set -e

echo "▸ انتظار قاعدة البيانات …"
python - <<'PY'
import os
import sys
import time

import psycopg

HOST = os.environ.get("POSTGRES_HOST", "postgres")
PORT = os.environ.get("POSTGRES_PORT", "5432")
NAME = os.environ.get("POSTGRES_DB", "walaee")
USER = os.environ.get("POSTGRES_USER", "walaee")

dsn = os.environ.get("DATABASE_URL")
if not dsn:
    dsn = "postgresql://{u}:{p}@{h}:{P}/{d}".format(
        u=USER,
        p=os.environ.get("POSTGRES_PASSWORD", ""),
        h=HOST,
        P=PORT,
        d=NAME,
    )

last = ""
for attempt in range(120):
    try:
        psycopg.connect(dsn, connect_timeout=3).close()
        sys.exit(0)
    except Exception as error:
        last = str(error).strip().splitlines()[0][:160]
        time.sleep(1)

# السبب الحقيقي يُطبع لا يُخمَّن: «تعذّر الاتصال» وحدها تترك من
# يقرأ السجل يفتّش في الشبكة بينما الخطأ كلمة مرور، أو العكس.
sys.stderr.write(
    "\n"
    "════════════════════════════════════════════════════\n"
    "✗ تعذّر الاتصال بقاعدة البيانات بعد دقيقتين\n"
    "  العنوان : " + HOST + ":" + PORT + "\n"
    "  القاعدة : " + NAME + "  ·  المستخدم: " + USER + "\n"
    "  آخر خطأ : " + last + "\n"
    "\n"
    "  المعتاد: POSTGRES_PASSWORD غير مضبوط في متغيّرات البيئة،\n"
    "  أو حجم قاعدة قديم يحتفظ بكلمة مروره الأولى مهما غُيّرت.\n"
    "════════════════════════════════════════════════════\n"
)
sys.exit(1)
PY

# العامل والمجدول لا يطبّقان الهجرات — نسخة واحدة تكفي وتفاديًا للتسابق
case "$1" in
  gunicorn)
    echo "▸ تطبيق الهجرات …"
    if ! python manage.py migrate --noinput; then
        echo ""
        echo "════════════════════════════════════════════════════"
        echo "✗ فشلت الهجرات — الحاوية تتوقف عمدًا."
        echo "  الخدمة على قاعدة غير مُهاجَرة تعطي سلوكًا خاطئًا لا"
        echo "  عطلًا ظاهرًا، وهو أسوأ بكثير من التوقف هنا."
        echo "════════════════════════════════════════════════════"
        exit 1
    fi

    echo "▸ تجميع الملفات الثابتة …"
    python manage.py collectstatic --noinput --clear ||
        echo "  ✗ تعذّر التجميع — لوحة الإدارة بلا تنسيق. يكمل الإقلاع."

    # المجدول يقرأ جدوله من قاعدة البيانات، وقاعدة جديدة تبدأ
    # فارغة — فيعمل beat بلا أن ينفّذ شيئًا ولا يظهر ذلك في أي
    # سجل. أول ما يُكتشف رصيد لم ينتهِ بعد سنة من موعده.
    echo "▸ تثبيت جدول المهام الدورية …"
    python manage.py install_schedule ||
        echo "  ✗ تعذّر التثبيت — المهام الدورية معطّلة. شغّل 'make schedule' لاحقًا."

    # شبكة التجّار المتعاقدين. ليست بيانات تجريبية — هي ما
    # تعرضه الصفحة العامة والخريطة، فتُزرع في كل بيئة بما فيها
    # الإنتاج. الأمر يُعاد تشغيله بلا ضرر ولا يدوس ما عدّله التاجر.
    #
    # فشله لا يُسقِط الإقلاع: دليل ناقص أهون بكثير من منصة لا تقوم.
    if [ "${WALAEE_SEED_NETWORK:-1}" = "1" ]; then
        echo "▸ تحديث شبكة التجّار …"
        python manage.py seed_network || echo "  ✗ تُخطّيت — الخريطة قد تظهر فارغة."
    fi

    # حسابات التجربة تُنشأ تلقائيًا حين يكون النشر تجريبيًا.
    # مطالبة من يجرّب المنتج بتشغيل أمر يدوي قبل أن يستطيع الدخول
    # هي عقبة بلا سبب — ولن يفعلها أحد.
    if [ -n "${DEMO_STAFF_PASSWORD:-}" ] || [ -n "${DEMO_LOGIN_PHONES:-}" ]; then
        echo "▸ تهيئة حسابات التجربة …"
        python manage.py demo_accounts --with-data \
            --password "${DEMO_STAFF_PASSWORD:-Walaee@2026}" ||
            echo "  ✗ تُخطّيت — شاشات الدخول بلا حسابات جاهزة."

        # تاريخ نشاط بحجم واقعي. شبكة بلا نشاط تُنتج لوحة
        # صحيحة وفارغة: كل مخطط خط على الصفر وكل مقارنة «—» —
        # فيبدو المنتج معطوبًا وهو سليم.
        #
        # يُشترط له ما يُشترط لحسابات التجربة نفسه: نشر تجريبي
        # وحده. والأمر يرفض العمل إن وجد مصدّات append-only مثبّتة
        # — حارس ثانٍ داخله لا يعتمد على هذا الشرط.
        SEED_ACTIVITY_LATER="${WALAEE_SEED_ACTIVITY:-1}"
    fi
    ;;
esac

# ══════════════════════════════════════════════════════════
#  البذرة الثقيلة تعمل **بعد** أن يبدأ الخادم، لا قبله.
#
#  `seed_activity` يكتب عشرات الآلاف من القيود عبر المحرك
#  الحقيقي، ويستغرق دقائق على خادم متواضع. تشغيله قبل `exec`
#  كان يُبقي المنفذ مغلقًا طوال تلك المدة، وفحص المنصّة الصحي
#  يفشل في تلك النافذة فتُعاد الحاوية — فتبدأ البذرة من جديد
#  ولا تنتهي أبدًا.
#
#  الترتيب الآن: الهجرات والشبكة والحسابات تحجب لأنها ثوانٍ
#  ويحتاجها أول زائر (الخريطة وشاشة الدخول)، والنشاط وحده
#  يتأخّر. الأمر مُصمَّم لإعادة التشغيل: يُكمّل ولا يضاعف،
#  فإيقاف الحاوية في منتصفه لا يفسد شيئًا.
# ══════════════════════════════════════════════════════════
if [ "${SEED_ACTIVITY_LATER:-0}" = "1" ]; then
    echo "▸ توليد تاريخ النشاط في الخلفية — الخادم يعمل الآن …"
    (
        if python manage.py seed_activity; then
            echo "▸ اكتمل توليد تاريخ النشاط"
        else
            echo "▸ تعذّر توليد تاريخ النشاط — راجع السجل. الخدمة تعمل."
        fi
    ) &
fi

echo "▸ تشغيل: $*"
exec "$@"
